// Export the raw vtable facts for GZCOM interfaces as YAML, one file per
// interface and program. Read-only: nothing in the database is changed.
//
//   mac <outDir> <iface>=<gziid> ...   run on the symbolized Mac x86-32 program
//   win <outDir> <iface> ...           run on SimCity 4.exe 1.1.641; reads <iface>.mac.yaml
//
// The Mac side supplies names, exact parameter types and the base offsets of
// each implementer. The Windows side supplies the slot order and extent that
// actually shipped. scripts/vtables.py aligns the two. See
// docs/RecoverInterfaceVtables.md.
//@category SC4

import ghidra.app.decompiler.DecompInterface;
import ghidra.app.decompiler.DecompileResults;
