    private List<Long> readSlots(Address start, Address pure) throws Exception {
        List<Long> slots = new ArrayList<>();
        for (Address p = start; slots.size() < MAX_SLOTS; p = p.add(4)) {
            long v = word(p);
            if ((pure == null || v != pure.getOffset()) && !isExec(v)) break;
            slots.add(v);
        }
        return slots;
    }

    private List<Long> readExecRun(Address start) {
        try {
            return readSlots(start, null);
        } catch (Exception e) {
            return List.of();
        }
    }

    private boolean isExec(long v) {
        try {
            if (v == 0) return false;
            MemoryBlock b = mem.getBlock(toAddr(v));
            return b != null && b.isExecute();
        } catch (Exception e) {
            return false;
        }
    }

    private Function resolve(Function f) {
        for (int hop = 0; f != null && hop < 4; hop++) {
            if (f.isThunk()) { f = f.getThunkedFunction(true); continue; }
            Instruction first = listing.getInstructionAt(f.getEntryPoint());
            Instruction next = first == null ? null : first.getNext();
            // Itanium this-adjusting thunk: ADD dword ptr [ESP+4],-K ; JMP impl
            if (first != null && first.getMnemonicString().equals("ADD") && next != null
                    && next.getMnemonicString().equals("JMP") && next.getFlows().length == 1) {
                Function t = getFunctionAt(next.getFlows()[0]);
                if (t == null || t.equals(f)) return f;
                f = t;
                continue;
            }
            return f;
        }
        return f;
    }

    private List<Long> immediateIds(Function f) {
        Set<Long> ids = new TreeSet<>();
        for (Instruction i : listing.getInstructions(f.getBody(), true)) {
            if (!Set.of("CMP", "SUB", "ADD", "XOR").contains(i.getMnemonicString())) continue;
            for (int op = 0; op < i.getNumOperands(); op++) {
                Scalar s = i.getScalar(op);
                if (s != null && s.getUnsignedValue() >= 0x1000) ids.add(s.getUnsignedValue());
            }
        }
        return new ArrayList<>(ids);
    }

    private int insns(Function f) {
        int n = 0;
        for (Instruction ignored : listing.getInstructions(f.getBody(), true)) n++;
        return n;
    }

    /** Direct call targets, through thunks. vtables.py turns these into slot-to-slot edges. */
    private List<Long> callees(Function f) {
        Set<Long> targets = new TreeSet<>();
        for (Instruction i : listing.getInstructions(f.getBody(), true)) {
            if (!i.getFlowType().isCall() && !(i.getFlowType().isJump() && i.getFlowType().isUnConditional())) continue;
            for (Address to : i.getFlows()) {
                if (f.getBody().contains(to)) continue;
                Function t = resolve(getFunctionAt(to));
                targets.add(t == null ? to.getOffset() : t.getEntryPoint().getOffset());
            }
        }
        return new ArrayList<>(targets);
    }

    /**
     * Slot indexes reached by CALL/JMP [reg+disp]. Overloads with the same ABI
     * (a pointer versus a reference) can only be told apart by which one wraps
     * the other, and the wrapper calls through the vtable. Calls through other
     * interfaces show up here too, as noise the alignment tolerates.
     */
    private List<Long> vcalls(Function f) {
        Set<Long> slots = new TreeSet<>();
        for (Instruction i : listing.getInstructions(f.getBody(), true)) {
            String m = i.getMnemonicString();
            if (!m.equals("CALL") && !m.equals("JMP")) continue;
            Object[] objs = i.getOpObjects(0);
            if (objs.length == 0 || !(objs[0] instanceof ghidra.program.model.lang.Register)) continue;
            long disp = 0;
            for (Object o : objs) if (o instanceof Scalar s) disp = s.getSignedValue();
            if (objs.length > 2 || disp < 0 || disp % 4 != 0 || disp >= 4L * MAX_SLOTS) continue;
            if (!i.getDefaultOperandRepresentation(0).contains("[")) continue;
            slots.add(disp / 4);
        }
        return new ArrayList<>(slots);
    }

    private List<String> strings(Function f) {
        List<String> found = new ArrayList<>();
        for (Instruction i : listing.getInstructions(f.getBody(), true)) {
            for (Reference r : i.getReferencesFrom()) {
                Data d = listing.getDataAt(r.getToAddress());
                if (d == null || !d.hasStringValue()) continue;
                String s = StringDataInstance.getStringDataInstance(d).getStringValue();
                if (s != null && !found.contains(s)) found.add(s.length() > 60 ? s.substring(0, 60) : s);
                if (found.size() >= MAX_STRINGS) return found;
            }
        }
        return found;
    }

    private Address symbol(String name) {
        for (Symbol s : currentProgram.getSymbolTable().getSymbols(name)) return s.getAddress();
        return null;
    }

    private long word(Address a) throws Exception {
        return mem.getInt(a) & 0xffffffffL;
    }

    private void line(String s) {
        out.append(s).append('\n');
    }

    private static String hex(long v) {
        return String.format("0x%08x", v);
    }

    private static String hexList(List<Long> values) {
        StringJoiner j = new StringJoiner(", ", "[", "]");
        for (long v : values) j.add(hex(v));
        return j.toString();
    }

    private static String quote(String s) {
        if (s == null) return "~";
        return "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"").replace("\n", "\\n").replace("\r", "\\r").replace("\t", "\\t").replaceAll("\\p{Cntrl}", " ") + "\"";
    }

    private static String quoteList(List<String> values) {
        StringJoiner j = new StringJoiner(", ", "[", "]");
        for (String v : values) j.add(quote(v));
        return j.toString();
    }
